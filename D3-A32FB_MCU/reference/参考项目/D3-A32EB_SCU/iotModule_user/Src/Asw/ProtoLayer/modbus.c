/* CRC16                                                                        */
/* puchMsg:  message to calculate CRC upon                                      */
/* usDataLen:  quantity of bytes in message                                     */
/*------------------------------------------------------------------------------*/
uint16_t CRC16(uint8_t *puchMsg, uint16_t usDataLen)
{
    uint8_t   uchCRCHi = 0xFF;                            /* high byte of CRC initialized */
    uint8_t   uchCRCLo = 0xFF;                            /* low byte of CRC initialized */
    uint8_t   uIndex;                                     /* will index into CRC lookup table */

    while(usDataLen--)                                  /* pass through message buffer */
    {
        uIndex = uchCRCHi ^ *puchMsg++;                 /* calculate the CRC */
        uchCRCHi = uchCRCLo ^ auchCRCHi[uIndex];
        uchCRCLo = auchCRCLo[uIndex];
    }
    return  (uchCRCHi << 8) | uchCRCLo;
}


uint16_t ModbusCRC(uint8_t *pData, uint32_t len)
{
    int crc = 0x0000ffff;
    int POLYNOMIAL = 0x0000a001;
    int i, j;
	
    for (i = 0; i < len; i++) {
        crc ^= ((int) pData[i] & 0x000000ff);
        for (j = 0; j < 8; j++) {
        	if ((crc & 0x00000001) != 0) {
            	crc >>= 1;
            	crc ^= POLYNOMIAL;
        	} else {
            	crc >>= 1;
        	}
        }
    }
    return crc;
}

//接收数据整理
uint8_t Modbus_Recv_CrcCheck(uint8_t *buf, uint16_t len)
{
  ModbusFrame *f = (ModbusFrame *) buf;
  uint8_t   *bp = &f->dev;

    uint16_t crc = (bp[len - 2] << 8) + bp[len - 1];
    uint16_t calc = CRC16 (bp, len - 2);
    if(crc != calc)
    {
      printf("crc != calc  0x%x  0x%x\r\n", crc, calc);
      return 0;
    }
    return 1;
}

ModbusFrame *MbsComm_ParsePack(STRU_MBUS_COMM_CONTEXT *g_pstuMbsCommHandle)
{
	E_UART_ERR e_UartErr = E_UART_NO_ERR;
	uint8_t*	pData = 0;//数据地址
	uint16_t	uLen = 0;//数据长度
	uint16_t	uPackLen = 0;//报文长度
	g_pstuMbsCommHandle->m_uRcvLen = 0;
	uLen = fgu16_UartRecvRoute(g_pstuMbsCommHandle->e_UartChnId, g_pstuMbsCommHandle->m_aucRcvBuf + g_pstuMbsCommHandle->m_uRcvLen, sizeof(g_pstuMbsCommHandle->m_aucRcvBuf) - g_pstuMbsCommHandle->m_uRcvLen, &e_UartErr);
	while(uLen)
	{
		g_pstuMbsCommHandle->m_uRcvLen += uLen;
		osDelay(1);
		uLen = fgu16_UartRecvRoute(g_pstuMbsCommHandle->e_UartChnId, g_pstuMbsCommHandle->m_aucRcvBuf + g_pstuMbsCommHandle->m_uRcvLen, sizeof(g_pstuMbsCommHandle->m_aucRcvBuf) - g_pstuMbsCommHandle->m_uRcvLen, &e_UartErr);
	}
	if(g_pstuMbsCommHandle->m_uRcvLen == 0 || uLen != 0)//当前接收缓存无数据，或数据帧接收未完毕
	{
		return NULL;
	}
  if (!Modbus_Recv_CrcCheck(g_pstuMbsCommHandle->m_aucRcvBuf, g_pstuMbsCommHandle->m_uRcvLen)) {  
		return NULL;
  }
  ModbusFrame *f = (ModbusFrame *)g_pstuMbsCommHandle->m_aucRcvBuf;

  fge_UartClearRxBufRoute(g_pstuMbsCommHandle->e_UartChnId);
  g_pstuMbsCommHandle->m_uRcvLen = 0;

	return f;
}

int32_t MbsComm_SendPack(STRU_MBUS_COMM_CONTEXT *g_pstuMbsCommHandle, uint8_t *p_data, uint16_t len)
{
  int32_t res = 0;
  E_UART_ERR e_UartErr;
	uint8_t   *bp = p_data;

	/* 计算CRC */
	uint16_t  crc;
	crc = CRC16 (p_data, len);

	bp[len++] = crc >> 8;
	bp[len++] = crc & 0xFF;

  e_UartErr = fge_CCU_UartDMASendRoute((uint8_t *)p_data, len);

  return res;
}


