void *myCalloc(size_t count, size_t sz)
{
    size_t totalSize = count * sz;
    uint8_t *ptr = (uint8_t *)pvPortMalloc(totalSize);

    if (ptr != NULL)
    {
        memset(ptr, 0, totalSize);
    }

    return ptr;
}


















