/* 排序,从小到大 */
void Common_InsertSort(uint16_t *a, uint16_t n)
{
	uint16_t i = 0,j = 0;
	uint16_t temp = 0;

	for( i = 1;i < n; i++ )
	{
		temp = a[i]; /*temp为要插入的元素*/
		j = i;  
		while( j > 0 && temp < a[j-1] )
		{ /*从a[i-1]开始找比a[i]小的数，同时把数组元素向后移*/
			a[j] = a[j-1];
			j--;
		}
		a[j] = temp; /*插入*/
	}
}























