void McalMCU_SystickInit(void)
{
    systick_clksource_set(SYSTICK_CLKSOURCE_HCLK);

    if(0U == SysTick_Config(SystemCoreClock / 1000U))
    {
        NVIC_SetPriority(SysTick_IRQn, 0x00U);
    }
}




























